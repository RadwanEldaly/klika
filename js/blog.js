// Blog Manager
window.BlogSystem = {
  currentCategory: 'all',
  activePostId: null,

  init() {
    this.renderPosts();
    this.bindEvents();
  },

  bindEvents() {
    const filterBtns = document.querySelectorAll('.blog-filter-btn');
    filterBtns.forEach(btn => {
      btn.addEventListener('click', () => {
        filterBtns.forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        this.currentCategory = btn.getAttribute('data-cat') || 'all';
        this.renderPosts();
      });
    });
  },

  renderPosts() {
    const container = document.getElementById('blog-grid');
    if (!container) return;

    const lang = window.KLIKA_LANG || 'ar';
    const dict = window.KLIKA_TRANSLATIONS[lang];

    const filtered = this.currentCategory === 'all'
      ? window.KLIKA_BLOG_POSTS
      : window.KLIKA_BLOG_POSTS.filter(p => p.category === this.currentCategory);

    container.innerHTML = filtered.map(post => {
      const title = lang === 'en' ? post.titleEn : post.titleAr;
      const excerpt = lang === 'en' ? post.excerptEn : post.excerptAr;
      const catLabel = this.getCategoryLabel(post.category, lang);

      return `
        <article class="blog-card" style="--card-accent: ${post.accent};">
          <div class="blog-card-inner">
            <div class="blog-card-meta">
              <span class="blog-tag">${catLabel}</span>
              <span class="blog-read-time">${post.readTime} ${dict.blogReadTimeSuffix}</span>
            </div>
            <h3 class="blog-card-title">${title}</h3>
            <p class="blog-card-excerpt">${excerpt}</p>
            <div class="blog-card-footer">
              <button class="btn-read-article" onclick="window.BlogSystem.openReader('${post.id}')" aria-label="Read article: ${title}">
                <span>${dict.blogReadMore}</span>
                <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
                  <path d="M5 12h14M12 5l7 7-7 7" />
                </svg>
              </button>
            </div>
          </div>
        </article>
      `;
    }).join('');
  },

  getCategoryLabel(cat, lang) {
    const dict = window.KLIKA_TRANSLATIONS[lang];
    if (cat === 'strategy') return dict.blogFilterStrategy;
    if (cat === 'ux') return dict.blogFilterUx;
    if (cat === 'growth') return dict.blogFilterGrowth;
    return dict.blogFilterAll;
  },

  openReader(postId) {
    const post = window.KLIKA_BLOG_POSTS.find(p => p.id === postId);
    if (!post) return;

    this.activePostId = postId;
    const modal = document.getElementById('blog-reader-modal');
    if (!modal) return;

    const lang = window.KLIKA_LANG || 'ar';
    const dict = window.KLIKA_TRANSLATIONS[lang];

    const title = lang === 'en' ? post.titleEn : post.titleAr;
    const body = lang === 'en' ? post.bodyEn : post.bodyAr;
    const catLabel = this.getCategoryLabel(post.category, lang);

    document.getElementById('reader-title').textContent = title;
    document.getElementById('reader-tag').textContent = catLabel;
    document.getElementById('reader-read-time').textContent = `${post.readTime} ${dict.blogReadTimeSuffix}`;
    document.getElementById('reader-body').innerHTML = body;

    modal.classList.add('active');
    document.body.style.overflow = 'hidden';
  },

  closeReader() {
    const modal = document.getElementById('blog-reader-modal');
    if (!modal) return;
    modal.classList.remove('active');
    document.body.style.overflow = '';
  }
};

